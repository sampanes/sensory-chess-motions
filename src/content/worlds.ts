// All built-in puzzles. Grid legend is in src/core/puzzle.ts.
// tests/levels.test.ts proves every one of these can be finished, so feel free
// to add or tweak levels -- `npm test` will tell you if one breaks.
//
// Level ids are permanent NAMES, not positions: saved stars are stored by id,
// so a level keeps its id wherever it moves. Never rename an id or reuse an
// old one; a new level takes the next unused number for its world.
//
// Levels play in the order listed, and tests/curve.test.ts checks that each
// world gets harder only gently. After adding levels, put every world back in
// order with `node scripts/sort-levels.ts`.

import type { Kind } from '../core/types.ts';

export type TreatKind = 'berry' | 'star' | 'carrot' | 'cupcake' | 'apple' | 'candy' | 'cookie';

export interface Level {
  id: string;
  grid: readonly string[];
}

export interface World {
  id: string;
  /** Friends shown on the world's bubble. */
  faces: readonly Kind[];
  treat: TreatKind;
  /** Background tint for this world's screens. */
  sky: string;
  /** Grown-up explanation, shown only in the grown-up panel. */
  lesson: string;
  levels: readonly Level[];
}

const world = (def: World): World => def;

/** One level: its permanent id, then the rows of its grid. */
function lv(id: string, ...grid: string[]): Level {
  return { id, grid };
}

